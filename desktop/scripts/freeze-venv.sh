#!/usr/bin/env bash
# Wave 2 — freeze relocatable venv into desktop/resources/venv/
#
# Usage:
#   ./desktop/scripts/freeze-venv.sh
#   SKIP_SYNC=1 ./desktop/scripts/freeze-venv.sh     # structure + relocate only (no uv sync)
#   SMOKE_ONLY=1 ./desktop/scripts/freeze-venv.sh    # create venv + pip/uv install langflow minimal smoke
#
# Requires: fetch-python-standalone.sh already populated resources/python/
# Requires (full freeze): uv on PATH, network for any missing wheels
#
# Launch contract (relocatable — prefer this over venv shebangs):
#   {resources/python}/bin/python -m langflow run ...
# with VIRTUAL_ENV={resources/venv} and site-packages from that venv
# (see SIDECAR.md).
#
# Linux lib path:
#   export LD_LIBRARY_PATH="{resources/python}/lib:$LD_LIBRARY_PATH"
# Windows PATH / DLL search (see .ps1 + SIDECAR.md):
#   prepend resources\python, resources\python\DLLs, resources\venv\Scripts
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "${SCRIPT_DIR}/lib/common.sh"

need_cmd uv

PY="$(resolve_standalone_python "${PYTHON_RES}")"
export_linux_lib_path "${PYTHON_RES}"

echo "==> freeze venv using ${PY}"
echo "    dest=${VENV_RES}"

rm -rf "${VENV_RES}"
mkdir -p "${RESOURCES_DIR}"

# Create venv from standalone interpreter (symlinks OK on Linux if we always launch via
# standalone python -m …; Windows freeze uses .ps1 + PATH/DLL prepend).
echo "==> creating venv"
"${PY}" -m venv --clear "${VENV_RES}"

# Relocatability: rewrite pyvenv.cfg home to a marker; runtime/shell resolves install dir.
rewrite_pyvenv_cfg() {
  local cfg="${VENV_RES}/pyvenv.cfg"
  [[ -f "${cfg}" ]] || die "missing ${cfg}"
  local abs_home
  abs_home="$(cd "$(dirname "${PY}")/.." && pwd)"
  # Keep version lines; set home relative marker for docs + optional rewrite at install.
  {
    echo "home = ${abs_home}"
    echo "include-system-site-packages = false"
    echo "version = $("${PY}" -c 'import sys; print("%d.%d.%d" % sys.version_info[:3])')"
    echo "executable = ${PY}"
    echo "command = ${PY} -m venv ${VENV_RES}"
    echo "# FarhadFlowCI: at package time, rewrite 'home'/'executable' to install-dir absolute paths"
    echo "# or always spawn via resources/python + PYTHONPATH/VIRTUAL_ENV (preferred)."
  } > "${cfg}"
}

rewrite_pyvenv_cfg

# Point uv at this venv + interpreter
export UV_PROJECT_ENVIRONMENT="${VENV_RES}"
export VIRTUAL_ENV="${VENV_RES}"

cd "${REPO_ROOT}"

VENV_PY="${VENV_RES}/bin/python"
[[ -x "${VENV_PY}" ]] || VENV_PY="${VENV_RES}/Scripts/python.exe"
[[ -x "${VENV_PY}" ]] || die "venv python missing after create"

if [[ "${SKIP_SYNC:-0}" == "1" ]]; then
  echo "==> SKIP_SYNC=1 — empty venv structure only"
elif [[ "${SMOKE_ONLY:-0}" == "1" ]]; then
  echo "==> SMOKE_ONLY=1 — install smoke deps into venv only (never mutate resources/python)"
  # Install into the venv interpreter — do NOT pass bare standalone ${PY} to uv pip
  # (that writes into resources/python site-packages and pollutes the frozen runtime).
  uv pip install --python "${VENV_PY}" --link-mode=copy httpx GitPython
else
  echo "==> uv sync into frozen venv (workspace, no-editable, no dev groups)"
  # --frozen respects uv.lock; --no-dev keeps size down; --link-mode=copy helps relocatable packs
  # --no-editable is required: sidecar launches standalone python + PYTHONPATH=venv site-packages.
  # PYTHONPATH does NOT process .pth files — editable installs → "No module named langflow" after relocate.
  # UV_PROJECT_ENVIRONMENT points installs at resources/venv.
  uv sync \
    --python "${PY}" \
    --frozen \
    --no-dev \
    --no-editable \
    --link-mode=copy \
    --project "${REPO_ROOT}"
fi

# Prefer launching with standalone python + venv site-packages (stable under relocate).
SITE="$(venv_site_packages "${VENV_RES}")"
LAUNCHER="${RESOURCES_DIR}/run-langflow.sh"
cat > "${LAUNCHER}" <<EOF
#!/usr/bin/env bash
# Generated by freeze-venv.sh — relocatable sidecar entry (do not use venv shebangs).
set -euo pipefail
ROOT="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
PY="\${ROOT}/python/bin/python3"
[[ -x "\${PY}" ]] || PY="\${ROOT}/python/bin/python"
[[ -x "\${PY}" ]] || PY="\${ROOT}/python/python.exe"
export VIRTUAL_ENV="\${ROOT}/venv"
export PATH="\${VIRTUAL_ENV}/bin:\${ROOT}/python/bin:\${PATH}"
export PYTHONNOUSERSITE=1
# Merge defaults from resources/env/default.env (do not override already-set vars).
# LANGFLOW_GIT_FLOWS_DIR intentionally unset by default → {config_dir}/flows-repo.
_ENV_FILE="\${ROOT}/env/default.env"
if [[ -f "\${_ENV_FILE}" ]]; then
  while IFS= read -r _line || [[ -n "\${_line}" ]]; do
    [[ -z "\${_line}" || "\${_line}" =~ ^[[:space:]]*# ]] && continue
    _key="\${_line%%=*}"
    _val="\${_line#*=}"
    _key="\${_key%"\${_key##*[![:space:]]}"}"
    _key="\${_key#"\${_key%%[![:space:]]*}"}"
    [[ -z "\${_key}" ]] && continue
    if [[ -z "\${!_key+x}" ]]; then
      export "\${_key}=\${_val}"
    fi
  done < "\${_ENV_FILE}"
fi
unset _ENV_FILE _line _key _val
if [[ -d "\${ROOT}/python/lib" ]]; then
  export LD_LIBRARY_PATH="\${ROOT}/python/lib\${LD_LIBRARY_PATH:+:\${LD_LIBRARY_PATH}}"
fi
# Ensure venv site-packages on path even if pyvenv.cfg home is stale after relocate
export PYTHONPATH="\${VIRTUAL_ENV}/lib/python\$("\${PY}" -c 'import sys;print("%d.%d"%sys.version_info[:2])')/site-packages\${PYTHONPATH:+:\${PYTHONPATH}}"
# Windows venv layout fallback handled in run-langflow.ps1
exec "\${PY}" -m langflow "\$@"
EOF
chmod +x "${LAUNCHER}"

# Trim fat — delete matching dirs carefully (depth-first via find -depth)
# NEVER delete dirs named test/tests/testing — numpy.testing (and others) are runtime APIs.
echo "==> size trim excludes"
if [[ -d "${VENV_RES}" ]]; then
  find "${VENV_RES}" -depth -type d \( -name '__pycache__' -o -name '.pytest_cache' \) -exec rm -rf {} + 2>/dev/null || true
  find "${VENV_RES}" -type f \( -name '*.pyc' -o -name '*.pyo' \) -delete 2>/dev/null || true
  # Unused torch (should already be excluded via all-no-torch; belt-and-suspenders)
  find "${VENV_RES}" -depth -type d \( -iname 'torch' -o -iname 'nvidia' \) -exec rm -rf {} + 2>/dev/null || true
  SITE="$(venv_site_packages "${VENV_RES}" 2>/dev/null || true)"
  if [[ -n "${SITE:-}" && -d "${SITE}" ]]; then
    find "${SITE}" -depth -type d \( -name 'docs' -o -name 'doc' -o -name 'examples' -o -name 'benchmarks' \) -exec rm -rf {} + 2>/dev/null || true
  fi
fi

# Strip absolute shebangs in venv/bin → use /usr/bin/env python3 (still prefer -m langflow)
if [[ -d "${VENV_RES}/bin" ]]; then
  echo "==> rewrite shebangs under venv/bin (relocatable)"
  while IFS= read -r -d '' f; do
    if head -n1 "${f}" | grep -q '^#!.*python'; then
      # Only touch text scripts
      if file -b "${f}" | grep -qi 'text\|script\|python'; then
        tmp="${f}.shebang.tmp"
        {
          echo '#!/usr/bin/env python3'
          tail -n +2 "${f}"
        } > "${tmp}"
        mv "${tmp}" "${f}"
        chmod +x "${f}"
      fi
    fi
  done < <(find "${VENV_RES}/bin" -type f -print0 2>/dev/null)
fi

rewrite_pyvenv_cfg

# Import smoke (full or smoke mode) — use venv python so site-packages resolve
if [[ "${SKIP_SYNC:-0}" != "1" ]]; then
  echo "==> import smoke"
  export VIRTUAL_ENV="${VENV_RES}"
  export PATH="${VENV_RES}/bin:${PYTHON_RES}/bin:${PATH}"
  export PYTHONNOUSERSITE=1
  export_linux_lib_path "${PYTHON_RES}"
  if [[ "${SMOKE_ONLY:-0}" == "1" ]]; then
    "${VENV_PY}" -c "import httpx, git; print('smoke imports OK', httpx.__version__)"
  else
    # Relocatable contract: standalone python + venv site on PYTHONPATH (must work without venv/bin).
    SITE="$(venv_site_packages "${VENV_RES}")"
    if find "${SITE}" -maxdepth 1 -name '_editable_impl_*.pth' -print -quit 2>/dev/null | grep -q .; then
      die "editable .pth still present under ${SITE} — freeze must use uv --no-editable"
    fi
    export PYTHONPATH="${SITE}${PYTHONPATH:+:${PYTHONPATH}}"
    unset VIRTUAL_ENV
    # Import path that previously broke when size-trim deleted numpy/testing.
    "${PY}" -c "import numpy.testing, scipy.signal, langflow, httpx, git; from langflow.main import setup_app; print('langflow', getattr(langflow,'__version__', '?'), langflow.__file__)"
  fi
fi

# Manifest for critical binaries
# shellcheck source=/dev/null
source "${SCRIPT_DIR}/write-manifest.sh"
write_resources_manifest

echo "OK: frozen venv at ${VENV_RES}"
echo "    launch via: ${LAUNCHER} run --host 127.0.0.1 --port 7860 --frontend-path ${FRONTEND_RES}"
